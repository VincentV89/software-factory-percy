import { readFile } from 'node:fs/promises';
import { expect, test, type Page } from '@playwright/test';
import { setUpFixtures, signIn, target } from './target';

const ROOT = 'platform-admin@percy.local';
async function agencyAndTeam(page: Page) {
  await setUpFixtures(page);
  await signIn(page, ROOT);
  await page.goto('/admin');
  const name = 'UI Agency ' + Date.now();
  await page.getByTestId('agency-form-name').fill(name);
  await page.getByTestId('agency-form-submit').click();
  await page.getByTestId('agency-select').filter({ hasText: name }).click();
  await page.getByTestId('team-form-name').fill('UI Team');
  await page.getByTestId('team-form-submit').click();
  await page.getByTestId('member-form-team').selectOption({ label: 'UI Team' });
  const teamId = await page.getByTestId('member-form-team').inputValue();
  return { teamId, agencyName: name };
}
async function addMember(page: Page, email: string, approver = false) {
  await page.getByTestId('member-form-email').fill(email);
  await page.getByTestId('member-form-approver').setChecked(approver);
  await page.getByTestId('member-form-submit').click();
  await expect(page.getByTestId('team-member-row').filter({ hasText: email })).toBeVisible();
}

test('UI journeys: invitations, membership revocation, fixtures, and CSRF check', async ({ page, browser }) => {
  test.skip(!target.local, 'Local invitation adapter verifies UI without sending real invitations.');
  test.setTimeout(120_000);
  const { teamId } = await agencyAndTeam(page);
  await page.getByTestId('invite-email').fill('ui-member@percy.local');
  await page.getByTestId('invite-submit').click();
  await expect(page.getByTestId('invite-notice')).toContainText('no email was sent');
  await addMember(page, 'ui-member@percy.local', true);
  const memberContext = await browser.newContext();
  const member = await memberContext.newPage();
  await signIn(member, 'ui-member@percy.local');
  await expect(member.getByTestId('campaigns-empty')).toBeVisible();
  const row = page.getByTestId('team-member-row').filter({ hasText: 'ui-member@percy.local' });
  await row.getByRole('button', { name: 'Remove approver role' }).click();
  await expect(row.getByRole('button', { name: 'Make approver' })).toBeVisible();
  page.once('dialog', (dialog) => void dialog.accept());
  await row.getByRole('button', { name: 'Remove member', exact: true }).click();
  await expect(row).toHaveCount(0);
  await member.reload();
  await expect(member.getByTestId('access-not-set-up')).toBeVisible();
  await addMember(page, ROOT);
  await page.reload();
  await page.getByTestId('nav-test-journeys').click();
  await page.getByTestId('journey-team').selectOption(teamId);
  await expect(page.getByTestId('journey-card')).toHaveCount(16);
  const fixtureTag = await page.getByTestId('fixture-tag').textContent();
  const firstJourney = page.getByTestId('journey-card').first();
  await firstJourney.locator('summary').click();
  await firstJourney.getByRole('checkbox').check();
  await page.goto('/admin');
  await page.getByTestId('nav-test-journeys').click();
  await expect(page.getByTestId('fixture-tag')).toHaveText(fixtureTag ?? '');
  await page.getByTestId('journey-card').first().locator('summary').click();
  await expect(page.getByTestId('journey-card').first().getByRole('checkbox')).toBeChecked();
  const downloadEvent = page.waitForEvent('download');
  await page.getByTestId('download-eicar.csv').click();
  const downloaded = await downloadEvent;
  const file = await downloaded.path();
  expect((await readFile(file ?? '')).length).toBe(68);
  await page.getByTestId('csrf-check').click();
  await expect(page.getByTestId('csrf-check-result')).toContainText('Passed: write refused (403)');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '/tmp/percy-ui-journeys-mobile.png', fullPage: true });
  await memberContext.close();
});

