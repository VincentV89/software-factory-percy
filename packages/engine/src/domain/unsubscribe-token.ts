import { base64url, constantTimeEqual, fromBase64url, hmacSha256 } from '@percy/shared';

/**
 * Unsubscribe token (FR-UNS-01, design 7.9):
 * base64url("v1.<kid>.<campaignId>.<agencyId>.<addrHash>") + "." + base64url(HMAC-SHA256).
 * It contains no readable email address; the kid lets keys rotate.
 */
export interface UnsubscribeClaims {
  kid: string;
  campaignId: string;
  agencyId: string;
  addrHash: string;
}

export interface UnsubscribeKeys {
  current: string;
  keys: Record<string, string>;
}

const SAFE = /^[A-Za-z0-9_-]+$/;

export function signUnsubscribeToken(claims: Omit<UnsubscribeClaims, 'kid'>, keys: UnsubscribeKeys): string {
  const kid = keys.current;
  const key = keys.keys[kid];
  if (!key) throw new Error('current unsubscribe key is missing');
  for (const v of [kid, claims.campaignId, claims.agencyId, claims.addrHash]) if (!SAFE.test(v)) throw new Error('token claim contains unsafe characters');
  const payload = ['v1', kid, claims.campaignId, claims.agencyId, claims.addrHash].join('.');
  return `${base64url(payload)}.${base64url(hmacSha256(key, payload))}`;
}

/** Returns the claims, or undefined for any malformed, unknown-key or tampered token. */
export function verifyUnsubscribeToken(token: string, keys: UnsubscribeKeys): UnsubscribeClaims | undefined {
  if (token.length > 512) return undefined;
  const [encoded, signature, extra] = token.split('.');
  if (!encoded || !signature || extra !== undefined) return undefined;
  let payload: string;
  try {
    payload = fromBase64url(encoded);
  } catch {
    return undefined;
  }
  const parts = payload.split('.');
  if (parts.length !== 5 || parts[0] !== 'v1') return undefined;
  const [, kid, campaignId, agencyId, addrHash] = parts as [string, string, string, string, string];
  const key = keys.keys[kid];
  if (!key) return undefined;
  if (!constantTimeEqual(base64url(hmacSha256(key, payload)), signature)) return undefined;
  if (!/^[0-9a-f]{64}$/.test(addrHash)) return undefined;
  return { kid, campaignId, agencyId, addrHash };
}

/**
 * Secrets Manager value: `{"current":"k1","k1":"<random>"}` (generated by CDK). A `keys` map is
 * also accepted. Rotation adds a new kid and moves `current`; old kids keep verifying.
 */
export function parseUnsubscribeSecret(raw: string): UnsubscribeKeys {
  const value = JSON.parse(raw) as { current?: string; keys?: Record<string, string> } & Record<string, unknown>;
  if (typeof value.current !== 'string') throw new Error('unsubscribe secret has no current kid');
  const keys = value.keys ?? Object.fromEntries(Object.entries(value).filter(([k, v]) => k !== 'current' && typeof v === 'string') as [string, string][]);
  if (!keys[value.current]) throw new Error('unsubscribe secret has no key for the current kid');
  return { current: value.current, keys };
}
